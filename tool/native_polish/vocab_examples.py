def apply_replacements():
    with VOCAB_CSV.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames
        assert fieldnames is not None
        rows = list(reader)

    changed = []
    for row in rows:
        korean = row["korean"]
        new_ex = REPLACEMENTS.get(korean)
        if new_ex and new_ex != row["example_korean"]:
            changed.append((korean, row["example_korean"], new_ex))
            row["example_korean"] = new_ex

    # write back
    backup = VOCAB_CSV.with_suffix(".csv.bak")
    if not backup.exists():
        shutil.copy2(VOCAB_CSV, backup)

    with VOCAB_CSV.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    return changed


