def lemma_components(lemma):
    return [part for word in lemma.split('+')
            for part in DERIVED_LEMMAS.get(word, (word,))]


def validate_choice_contract(entry):
    """Reject missing task evidence; this does not certify semantic quality."""
    if not entry['de_ex'].strip() or not entry['en_ex'].strip():
        raise ValueError(f"{entry['word']}: translated prompts are required")
    design = entry['choice_design']
    if not design['cueKo'].strip():
        raise ValueError(f"{entry['word']}: missing target meaning")
    tokens = [token.strip('.,!?') for token in entry['ko'].split()]
    for kind, expected in (('cloze', 3), ('satz', 2)):
        choices = design[kind]
        required = {'text', 'lemma', 'contrastKo'}
        if kind == 'satz':
            required.add('replaces')
        if any(set(choice) != required for choice in choices):
            raise ValueError(f"{entry['word']}: missing or extra {kind} choice fields")
        texts = [c['text'] for c in choices]
        if len(texts) != expected or len(set(texts)) != expected:
            raise ValueError(f"{entry['word']}: invalid {kind} choice count")
        for choice in choices:
            if any(not str(v).strip() for v in choice.values()):
                raise ValueError(f"{entry['word']}: empty {kind} choice metadata")
            if choice['text'] == entry['answer'] or choice['text'] in tokens:
                raise ValueError(f"{entry['word']}: answer/target tile in {kind} choices")
            if kind == 'satz' and choice['replaces'] not in tokens:
                raise ValueError(f"{entry['word']}: missing Satz replacement token")


