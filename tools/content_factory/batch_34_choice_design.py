"""Authored, translation-supported Batch 34 choices; never a random word pool.

The user's 2026-09-16 approved contract permits grammatical alternatives
when they do not express the supplied DE/EN prompt. No KO-only uniqueness
or human approval is implied. Satz alternatives name the token they replace
and are authored independently of the three cloze alternatives.
"""


def C(*items):
    if any(len(s.split('|')) != 3 for s in items):
        raise ValueError('Cloze choice requires text, lemma, and contrastKo')
    return [dict(zip(('text', 'lemma', 'contrastKo'), s.split('|'))) for s in items]


def T(*items):
    if any(len(s.split('|')) != 4 for s in items):
        raise ValueError('Satz choice requires replaces, text, lemma, and contrastKo')
    return [dict(zip(('replaces', 'text', 'lemma', 'contrastKo'), s.split('|'))) for s in items]


def D(cue, cloze, satz):
    return {'cueKo': cue, 'cloze': cloze, 'satz': satz}


