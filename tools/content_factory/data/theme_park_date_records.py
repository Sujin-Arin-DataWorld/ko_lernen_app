Triad = tuple[str, str, str]

LIVE_ID_BASE = {
    "a1": 90,
    "a2": 83,
    "b1": 78,
    "b2": 118,
    "c1": 77,
    "c2": 76,
}


def _turn(values: Triad, *, turn_kind: str | None = None) -> dict[str, str]:
    ko, de, en = values
    result = {"ko": ko, "de": de, "en": en}
    if turn_kind is not None:
        return {"turnKind": turn_kind, **result}
    return result


def _record(
    level: str,
    index: int,
    scene: str,
    kind: str,
    primary: Triad,
    *,
    alternative: Triad,
    follow_up: Triad,
    reply: Triad | None = None,
    relationship: str = "romantic_partner",
    target: str,
    evidentiality: str = "",
    modal_force: str = "",
    presupposition: str = "",
    triad_status: str = "MODEL_QA_PASS",
    critical_codes: str = "",
    field_notes: str,
) -> dict[str, Any]:
    record: dict[str, Any] = {
        "id": f"smalltalk_{level}_{LIVE_ID_BASE[level] + index:04d}",
        "category": "theme_park_date",
        "level": level,
        "kind": kind,
        **_turn(primary),
        "relationshipContext": relationship,
        "safeAlternativeQuestions": [
            _turn(alternative, turn_kind="question"),
        ],
        "followUp": _turn(follow_up, turn_kind="reaction"),
        "audit": {
            "scene": scene,
            "pedagogicalTarget": target,
            "evidentiality": evidentiality,
            "modalForce": modal_force,
            "presupposition": presupposition,
            "triadStatus": triad_status,
            "criticalCodes": critical_codes,
            "fieldNotes": field_notes,
        },
    }
    if reply is not None:
        record["reply"] = _turn(reply)
    return record


