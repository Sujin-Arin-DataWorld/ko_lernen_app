def production(phase_id, sources, rows=None):
    recognition = {t['requirementKeys'][0]: t for t in sources
                   if ':grammar:' in t['id']}
    result = []
    for index, (key, practice, assessment) in enumerate(rows if rows is not None else ROWS[phase_id], 1):
        lesson = recognition[key]
        def make(row):
            facts, answer, error = row
            explanation = loc(
                f'예: {answer} 의미가 다른 예: {error} 지정된 정보·관계·말투를 유지하세요. 다른 적절한 표현은 미채점으로 남을 수 있어요.',
                f'Example: {answer} Meaning or register error: {error} Preserve the given facts, relationships and register. Other valid wording may remain unscored.',
                f'Beispiel: {answer} Fehler bei Bedeutung oder Register: {error} Behalte Angaben, Beziehungen und Sprachstil bei. Andere passende Formulierungen können unbewertet bleiben.')
            return packet(facts, [sentence('sentence', loc(
                '조건에 맞는 완전한 문장을 쓰세요.',
                'Write a complete sentence that meets the given conditions.',
                'Schreibe einen vollständigen Satz, der die Vorgaben erfüllt.'),
                [answer], [error], explanation)], 'form')
